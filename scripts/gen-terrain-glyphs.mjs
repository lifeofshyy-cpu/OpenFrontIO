const CODE = { ".": 0, "#": 1, o: 2, "+": 3, x: 4, w: 5, g: 6 };
const rows = [];
for (const [name, art] of Object.entries(GLYPHS)) {
  const lines = art.split("\n").filter((l) => l.length > 0);
  if (lines.length > 16) throw new Error(`${name}: more than 16 rows`);
  while (lines.length < 16) lines.unshift("");
  for (const line of lines) {
    if (line.length > 16) throw new Error(`${name}: row wider than 16`);
    const padded = line.padEnd(16, ".");
    for (const half of [padded.slice(0, 8), padded.slice(8)]) {
      let v = 0n;
      for (const ch of half) {
        if (!(ch in CODE)) throw new Error(`${name}: bad character "${ch}"`);
        v = (v << 4n) | BigInt(CODE[ch]);
      }
      rows.push(`0x${v.toString(16).padStart(8, "0")}u`);
    }
  }
}

const count = Object.keys(GLYPHS).length;
let block = `const int GLYPH_COUNT = ${count};\n`;
block += `const uint GLYPH_ROWS[${rows.length}] = uint[${rows.length}](\n`;
for (let i = 0; i < rows.length; i += 4) {
  const last = i + 4 >= rows.length;
  block += `  ${rows.slice(i, i + 4).join(", ")}${last ? "" : ","}\n`;
}
block += ");\n";

const file = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "../src/client/render/gl/shaders/terrain/terrain.frag.glsl",
);
const src = fs.readFileSync(file, "utf8");
const begin = "// GLYPH-DATA-BEGIN (generated by scripts/gen-terrain-glyphs.mjs)\n";
const end = "// GLYPH-DATA-END\n";
const a = src.indexOf(begin);
const b = src.indexOf(end);
if (a < 0 || b < 0) throw new Error("glyph data markers not found");
fs.writeFileSync(file, src.slice(0, a + begin.length) + block + src.slice(b));
console.log(`wrote ${count} glyphs`);
