// Generates the pixel-art glyph bitmaps used by the fantasy-map terrain
// shader, and writes them between the GLYPH-DATA markers in
// src/client/render/gl/shaders/terrain/terrain.frag.glsl.
//
//   node scripts/gen-terrain-glyphs.mjs
//
// Each glyph is 16x16, 4 bits per pixel, two uints per row (left half, then
// right half):
//   .  transparent   #  outline   o  light   +  main   x  shadow   w  white
//   g  shaded grass
// Rows shorter than 16 are padded on the right; missing rows are added on top.
